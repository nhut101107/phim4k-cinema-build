const crypto = require('crypto');
const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const publicRoot = path.join(root, 'ios', 'App', 'App', 'public');
const output = path.join(root, 'ios', 'App', 'App', 'RuntimeIntegrityManifest.generated.swift');

if (!fs.existsSync(path.join(publicRoot, 'index.html'))) {
  throw new Error('Run Capacitor iOS sync before generating the integrity manifest.');
}

function walk(directory) {
  return fs.readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
    const absolute = path.join(directory, entry.name);
    if (entry.isDirectory()) return walk(absolute);
    if (!entry.isFile() || entry.name === '.DS_Store' || entry.name.endsWith('.map')) return [];
    return [absolute];
  });
}

const entries = walk(publicRoot)
  .map((absolute) => {
    const relative = `public/${path.relative(publicRoot, absolute).split(path.sep).join('/')}`;
    const digest = crypto.createHash('sha256').update(fs.readFileSync(absolute)).digest('hex');
    return [relative, digest];
  })
  .sort(([left], [right]) => left.localeCompare(right));

if (!entries.some(([file]) => file === 'public/index.html')) {
  throw new Error('Integrity manifest is missing public/index.html.');
}

const table = entries
  .map(([file, digest]) => `        ${JSON.stringify(file)}: ${JSON.stringify(digest)},`)
  .join('\n');

const swift = `// Generated by scripts/generate-ios-integrity-manifest.js. Do not edit manually.
import CryptoKit
import Foundation

enum RuntimeIntegrityManifest {
    private static let protectedFiles: [String: String] = [
${table}
    ]

    static func verify(in bundle: Bundle = .main) -> Bool {
        guard let resourceRoot = bundle.resourceURL else { return false }
        let publicRoot = resourceRoot.appendingPathComponent("public", isDirectory: true)
        guard let enumerator = FileManager.default.enumerator(
            at: publicRoot,
            includingPropertiesForKeys: [.isRegularFileKey],
            options: [.skipsHiddenFiles]
        ) else { return false }

        var actualFiles = Set<String>()
        for case let url as URL in enumerator {
            guard (try? url.resourceValues(forKeys: [.isRegularFileKey]).isRegularFile) == true else { continue }
            let prefix = publicRoot.path + "/"
            guard url.path.hasPrefix(prefix) else { return false }
            let relative = "public/" + String(url.path.dropFirst(prefix.count))
            if relative.hasSuffix(".map") { return false }
            actualFiles.insert(relative)
        }

        guard actualFiles == Set(protectedFiles.keys) else { return false }
        for (relative, expectedDigest) in protectedFiles {
            let url = resourceRoot.appendingPathComponent(relative, isDirectory: false)
            guard let data = try? Data(contentsOf: url, options: .mappedIfSafe) else { return false }
            let digest = SHA256.hash(data: data).map { String(format: "%02x", $0) }.joined()
            guard digest == expectedDigest else { return false }
        }
        return true
    }
}
`;

fs.writeFileSync(output, swift, 'utf8');
console.log(`Generated iOS integrity manifest for ${entries.length} files.`);
